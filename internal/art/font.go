// TextWidth is the width in pixels of s in the 5x7 font (1px spacing).
func TextWidth(s string) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*6 - 1
}

// Text draws s with its top-left corner at (x, y). Unknown runes draw blank.
func (l *Layer) Text(x, y int, s string, c RGB) {
	for _, r := range strings.ToUpper(s) {
		if g, ok := glyphs[r]; ok {
			for j, row := range g {
				for i, ch := range row {
					if ch == '#' {
						l.Set(x+i, y+j, c)
					}
				}
			}
		}
		x += 6
	}
}

// FontJS exports the font as a JavaScript module so the games draw text in
// the same pixel font as the titles. Each glyph is 7 rows of 5-bit masks.
func FontJS() string {
	keys := make([]string, 0, len(glyphs))
	for r := range glyphs {
		keys = append(keys, string(r))
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("// Generated by `go run ./cmd/artgen` from internal/art/font.go. Do not edit.\n")
	b.WriteString("export const GLYPHS = {\n")
	for _, k := range keys {
		g := glyphs[[]rune(k)[0]]
		masks := make([]string, 7)
		for i, row := range g {
			v := 0
			for _, ch := range row {
				v <<= 1
				if ch == '#' {
					v |= 1
				}
			}
			masks[i] = strconv.Itoa(v)
		}
		fmt.Fprintf(&b, "  %s: [%s],\n", strconv.Quote(k), strings.Join(masks, ", "))
	}
	b.WriteString("};\n")
	return b.String()
}

// Supported reports whether every rune in s has a glyph.
func Supported(s string) bool {
	for _, r := range strings.ToUpper(s) {
		if _, ok := glyphs[r]; !ok {
			return false
		}
	}
	return true
}
