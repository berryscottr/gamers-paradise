// TestGeneratedFilesAreCurrent fails when the committed art differs from
// what this code draws. Fix: go run ./cmd/artgen
func TestGeneratedFilesAreCurrent(t *testing.T) {
	files, err := Render()
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join("..", "web", "static", "art")
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Errorf("%s: %v (run go run ./cmd/artgen)", name, err)
			continue
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is stale: run go run ./cmd/artgen", name)
		}
	}
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if _, ok := files[e.Name()]; !ok {
			t.Errorf("%s is not generated by artgen: delete it", e.Name())
		}
	}
}

func TestRenderIsDeterministic(t *testing.T) {
	a, _ := Render()
	b, _ := Render()
	for k := range a {
		if !bytes.Equal(a[k], b[k]) {
			t.Errorf("%s differs between runs", k)
		}
	}
}

func TestPhasesCoverEveryHour(t *testing.T) {
	want := map[int]string{0: "night", 1: "night", 2: "latenight", 4: "latenight", 5: "morning", 11: "afternoon", 17: "dusk", 21: "night", 23: "night"}
	for h, name := range want {
		if got := PhaseAt(h).Name; got != name {
			t.Errorf("hour %d: %s, want %s", h, got, name)
		}
	}
	for i := 1; i < len(Phases); i++ {
		if Phases[i].FromHour <= Phases[i-1].FromHour {
			t.Error("phases must be in clock order")
		}
	}
}

func TestHotspotsFitTheRoom(t *testing.T) {
	seen := map[string]bool{}
	for _, h := range Hotspots {
		if seen[h.ID] {
			t.Errorf("duplicate hotspot %s", h.ID)
		}
		seen[h.ID] = true
		if h.X < 0 || h.Y < 0 || h.X+h.W > RoomW || h.Y+h.H > RoomH || h.W <= 0 || h.H <= 0 {
			t.Errorf("hotspot %s is outside the room", h.ID)
		}
		if h.Label == "" {
			t.Errorf("hotspot %s has no label", h.ID)
		}
	}
	if !strings.Contains(HotspotCSS(), ".hs-beanbag{") {
		t.Error("hotspot CSS missing an entry")
	}
}

func TestTitlesUseKnownGlyphs(t *testing.T) {
	for _, ti := range Titles {
		if !Supported(ti.Text) {
			t.Errorf("title %q has a character the font can't draw", ti.Text)
		}
	}
	if !Supported("SCORE 0123456789 + X : BEST STREAK") {
		t.Error("game HUD text not drawable")
	}
}

